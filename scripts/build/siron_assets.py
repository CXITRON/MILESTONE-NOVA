#!/usr/bin/env python3
"""Generate the Siron UI glyphs and phrase table compiled into NOVA.

Inputs (the conlang project is the source of truth for letters and spelling):
  ~/Documents/Dev/conlang/font/Siron-16.bdf   16 px bitmap, device codepoints U+E000-E029
  ~/Documents/Dev/conlang/font/charmap.tsv    letter order (same order as the BDF)
  ~/Documents/Dev/conlang/dictionary/server.py spelling(): validates and spells Siron words
  assets/siron/ui-strings.tsv                 Korean screen text -> Siron romanization
Outputs (checked in, so firmware builds do not need the conlang project):
  src/display/SironFont.cpp, src/ui/SironStrings.cpp

Romanization rules: {braces} keep English as is, printf specifiers (%s, %d) stay, every other
run of lowercase letters and ^ must be a valid Siron spelling or generation fails.
Usage: python3 scripts/build/siron_assets.py [--conlang DIR] [--check]
"""
import argparse
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DEVICE_BASE = 0xE000
HEIGHT = 16


def load_glyphs(conlang):
    rows = list(csv.DictReader(open(conlang / "font" / "charmap.tsv", encoding="utf-8"),
                               delimiter="\t"))
    text = (conlang / "font" / "Siron-16.bdf").read_text(encoding="ascii")
    glyphs = {}
    for m in re.finditer(r"ENCODING (\d+).*?DWIDTH (\d+) 0.*?BITMAP\n(.*?)ENDCHAR", text, re.S):
        code, width, bitmap = int(m.group(1)), int(m.group(2)), m.group(3).split()
        if len(bitmap) != HEIGHT or not 0 < width <= 16:
            sys.exit(f"bad glyph U+{code:04X}")
        nbytes = (width + 7) // 8
        glyphs[code] = (width, [int(r, 16) << (16 - nbytes * 8) for r in bitmap])
    if sorted(glyphs) != list(range(DEVICE_BASE, DEVICE_BASE + len(rows))):
        sys.exit("BDF does not cover the charmap in order")
    # Font codepoint (U+F0000...) -> device codepoint, by charmap order like make_bitmap.py.
    remap = {chr(int(r["codepoint"][2:], 16)): chr(DEVICE_BASE + i) for i, r in enumerate(rows)}
    return glyphs, remap


def convert(roman, spelling, remap):
    out, pos = [], 0
    for m in re.finditer(r"\{([^{}]*)\}|%[sd]|[a-z^]+", roman):
        out.append(roman[pos:m.start()])
        token = m.group(0)
        if token.startswith("{"):
            out.append(m.group(1))
        elif token.startswith("%"):
            out.append(token)
        else:
            _, glyph = spelling(token)
            out.append("".join(remap.get(ch, ch) for ch in glyph))
        pos = m.end()
    out.append(roman[pos:])
    return "".join(out)


def specifiers(text):
    return re.findall(r"%[sd]", text)


def c_string(text):
    out = []
    for byte in text.encode("utf-8"):
        out.append(chr(byte) if 32 <= byte < 127 and chr(byte) not in '"\\?' else f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--conlang", type=pathlib.Path,
                        default=pathlib.Path.home() / "Documents/Dev/conlang")
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    sys.path.insert(0, str(args.conlang / "dictionary"))
    from server import Problem, spelling  # noqa: E402

    glyphs, remap = load_glyphs(args.conlang)
    phrases = {}
    for n, line in enumerate((ROOT / "assets/siron/ui-strings.tsv").read_text(
            encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        korean, roman, _ = line.split("\t")
        if korean in phrases:
            sys.exit(f"ui-strings.tsv:{n}: duplicate {korean!r}")
        try:
            siron = convert(roman, spelling, remap)
        except Problem as error:
            sys.exit(f"ui-strings.tsv:{n}: {roman!r}: {error}")
        if specifiers(korean) != specifiers(siron):
            sys.exit(f"ui-strings.tsv:{n}: format specifiers differ")
        phrases[korean] = siron

    font = ["// Generated by scripts/build/siron_assets.py from conlang font/Siron-16.bdf.",
            "// Do not edit; regenerate instead.", '#include "SironFont.h"',
            "namespace nova::siron {", "namespace {", "const Glyph glyphs[glyphCount]{"]
    for code in sorted(glyphs):
        width, rows = glyphs[code]
        font.append(f"    {{{width}, {{{', '.join(f'0x{r:04X}' for r in rows)}}}}},")
    font += ["};", "} // namespace", "const Glyph *glyph(uint32_t codepoint) {",
             "  return codepoint >= firstCodepoint && codepoint < firstCodepoint + glyphCount",
             "             ? &glyphs[codepoint - firstCodepoint]", "             : nullptr;",
             "}", "} // namespace nova::siron", ""]

    table = ["// Generated by scripts/build/siron_assets.py from assets/siron/ui-strings.tsv.",
             "// Do not edit; regenerate instead. Sorted by Korean text (strcmp order).",
             '#include "Language.h"', "namespace nova::siron {",
             "const Phrase phrases[]{"]
    for korean in sorted(phrases, key=lambda k: k.encode("utf-8")):
        table.append(f"    {{{c_string(korean)}, {c_string(phrases[korean])}}},")
    table += ["};", "const unsigned phraseCount = sizeof(phrases) / sizeof(phrases[0]);",
              "} // namespace nova::siron", ""]

    outputs = {ROOT / "src/display/SironFont.cpp": "\n".join(font),
               ROOT / "src/ui/SironStrings.cpp": "\n".join(table)}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale:
            sys.exit("stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
    print(f"{len(glyphs)} glyphs, {len(phrases)} phrases;",
          "updated " + (", ".join(str(p.relative_to(ROOT)) for p in stale) or "nothing"))


if __name__ == "__main__":
    main()
